// Offline app shell for the production build. Network-first for same-origin
// GETs, falling back to the last cached copy. Model weights are cached
// separately by Transformers.js (Cache Storage "transformers-cache").
const CACHE = "trace-shell-v1";

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      })
      .catch(async () => (await caches.match(req, { ignoreSearch: req.mode === "navigate" })) ?? Response.error()),
  );
});
